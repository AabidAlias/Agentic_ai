import uuid
import streamlit as st
from langchain_core.messages import HumanMessage, AIMessage, AIMessageChunk

# Import your compiled graph and thread retrieval function from your backend
from Langgraph_DB_back import chatbot, retrive_all_thread

st.set_page_config(page_title="LangGraph Chatbot", page_icon="🤖", layout="wide")

# ---------------------------------------------------------
# Helper Function to Clean Gemini List Content
# ---------------------------------------------------------
def extract_text(content):
    if isinstance(content, list):
        return "".join(
            block.get("text", "") for block in content 
            if isinstance(block, dict) and block.get("type") == "text"
        )
    return str(content) if content else ""

# Generator function to stream tokens from LangGraph
def stream_langgraph_response(prompt, config):
    for chunk, metadata in chatbot.stream(
        {"messages": [HumanMessage(content=prompt)]},
        config=config,
        stream_mode="messages"
    ):
        # Only yield chunks generated by the AI model
        if isinstance(chunk, AIMessageChunk) and chunk.content:
            text_piece = extract_text(chunk.content)
            if text_piece:
                yield text_piece

# ---------------------------------------------------------
# 1. Session State Initialization
# ---------------------------------------------------------
if "thread_id" not in st.session_state:
    st.session_state.thread_id = str(uuid.uuid4())

if "messages" not in st.session_state:
    st.session_state.messages = []

# Helper function to load past messages from LangGraph's checkpointer
def load_chat_history(thread_id):
    config = {"configurable": {"thread_id": thread_id}}
    state = chatbot.get_state(config)
    
    loaded_messages = []
    if state and "messages" in state.values:
        for msg in state.values["messages"]:
            if isinstance(msg, HumanMessage):
                loaded_messages.append({"role": "user", "content": extract_text(msg.content)})
            elif isinstance(msg, AIMessage) and msg.content:
                loaded_messages.append({"role": "assistant", "content": extract_text(msg.content)})
    return loaded_messages

# ---------------------------------------------------------
# 2. Sidebar: New Chat & Thread History
# ---------------------------------------------------------
with st.sidebar:
    st.title("💬 Conversations")
    
    # Button to start a brand new thread
    if st.button("➕ New Chat", use_container_width=True, type="primary"):
        st.session_state.thread_id = str(uuid.uuid4())
        st.session_state.messages = []
        st.rerun()

    st.divider()
    st.subheader("Saved Threads")

    # Fetch all existing thread IDs from your backend function
    try:
        threads = retrive_all_thread()
    except Exception as e:
        threads = []
        st.error(f"Error loading threads: {e}")

    # Display each thread as a clickable button in the sidebar
    if threads:
        for t_id in reversed(threads):
            is_active = (t_id == st.session_state.thread_id)
            button_label = f"🟢 {t_id[:8]}..." if is_active else f"💬 {t_id[:8]}..."
            
            if st.button(button_label, key=t_id, use_container_width=True):
                st.session_state.thread_id = t_id
                st.session_state.messages = load_chat_history(t_id)
                st.rerun()
    else:
        st.caption("No saved conversations yet.")

# ---------------------------------------------------------
# 3. Main Chat Interface
# ---------------------------------------------------------
st.title("🤖 AI Assistant")
st.caption(f"Current Thread ID: `{st.session_state.thread_id}`")

# Render existing chat messages on screen
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# Handle user input
if prompt := st.chat_input("Type your message here..."):
    # 1. Display user message immediately
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    # 2. Stream response from your LangGraph backend
    config = {"configurable": {"thread_id": st.session_state.thread_id}}
    
    with st.chat_message("assistant"):
        # st.write_stream renders chunks live and returns the full combined text when finished
        ai_reply = st.write_stream(stream_langgraph_response(prompt, config))

    # 3. Save complete AI reply to Streamlit session state
    st.session_state.messages.append({"role": "assistant", "content": ai_reply})
    
    # Rerun once if this was the first message so the new thread_id pops up in the sidebar
    if len(st.session_state.messages) == 2:
        st.rerun()
